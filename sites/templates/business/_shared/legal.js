/*!
 * legal.js — юридические страницы шаблона из config.js (группа legal).
 * Тексты основаны на sites/legal/*.md (152-ФЗ). Это шаблоны, а не юридическая консультация.
 *
 * Страница: <body data-doc="privacy|consent|cookies"><main id="doc"></main>
 *           <script src="../config.js"></script><script src="../../_shared/legal.js"></script>
 * Если владелец положил свой утверждённый текст в legal.docs.<doc> (строка HTML), выводится он.
 * Незаполненные поля видны как [ПЛЕЙСХОЛДЕР] — их заполняет владелец сайта.
 */
(function () {
  'use strict';
  var C = window.SITE_CONFIG || {}, L = C.legal || {}, B = C.brand || {}, M = C.meta || {};
  var doc = document.body.getAttribute('data-doc');
  var esc = function (s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };
  var f = function (v, ph) { return v ? esc(v) : '<mark class="fill">[' + ph + ']</mark>'; };
  var demo = M.mode !== 'production';

  var OP = f(L.operator, 'ЮРИДИЧЕСКОЕ ЛИЦО'), INN = f(L.inn, 'ИНН'), ADDR = f(L.address, 'ЮРИДИЧЕСКИЙ АДРЕС');
  var SITE = f(L.site, 'АДРЕС САЙТА'), EMAIL = f(L.email, 'ПОЧТА ДЛЯ ЗАПРОСОВ ПО ДАННЫМ'), DATE = f(L.effectiveDate, 'ДАТА');
  var PHONE = L.phone ? esc(L.phone) : (C.contacts && C.contacts.phone ? esc(C.contacts.phone) : '');
  var list = function (arr) { return '<ul>' + arr.map(function (x) { return '<li>' + x + '</li>'; }).join('') + '</ul>'; };
  var data = (L.dataCollected || []).map(esc);
  var processors = (L.processors || []).map(esc);
  var metrika = C.integrations && C.integrations.analytics && C.integrations.analytics.yandexMetrika;

  var DOCS = {
    privacy: {
      title: 'Политика в отношении обработки персональных данных',
      body: function () {
        return '<p class="doc-meta">Дата вступления в силу: ' + DATE + '<br>Оператор: ' + OP + ' (ИНН ' + INN + '), адрес: ' + ADDR + '<br>Сайт: ' + SITE + '</p>' +
          '<h2>1. Общие положения</h2><p>Политика составлена в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных». Она описывает, какие данные обрабатывает ' + OP + ' (далее — Оператор) и как их защищает.</p>' +
          '<h2>2. Какие данные мы обрабатываем</h2>' + list(['имя;', 'номер телефона, адрес почты или ник в Telegram — то, что вы указали для связи;']
            .concat(data.length ? data.map(function (d) { return d + ';'; }) : ['сведения, которые вы сами указали в форме заявки;'])
            .concat(['технические данные: страница отправки заявки, метки источника перехода (UTM), IP-адрес — для защиты от спама.'])) +
          '<p>Мы не просим указывать в формах сведения о здоровье, паспортные данные и данные банковских карт.</p>' +
          '<h2>3. Цели обработки</h2>' + list(['ответ на заявку и связь с вами;', 'подготовка расчёта, записи или договора по вашему запросу;', 'исполнение требований законодательства РФ.']) +
          '<h2>4. Правовые основания</h2><p>Ваше согласие на обработку персональных данных, договор с вами, требования законодательства РФ.</p>' +
          '<h2>5. Как хранятся данные</h2><p>Заявки хранятся на сервере Оператора' + (processors.length ? '. Для уведомлений и учёта заявок Оператор использует: ' + processors.join(', ') + '.' : '.') + ' Данные обрабатываются до достижения целей обработки или до отзыва согласия, затем удаляются или обезличиваются в сроки, установленные 152-ФЗ.</p>' +
          '<h2>6. Передача третьим лицам</h2><p>Оператор не передаёт данные третьим лицам, кроме случаев, когда вы дали согласие, передача нужна для исполнения договора с вами или предусмотрена законом.</p>' +
          '<h2>7. Защита данных</h2><p>Оператор принимает правовые, организационные и технические меры: ограничивает доступ к заявкам, использует защищённое соединение и резервное копирование.</p>' +
          '<h2>8. Ваши права</h2>' + list(['получить сведения об обработке ваших данных;', 'потребовать уточнения, блокирования или удаления данных;', 'отозвать согласие;', 'обжаловать действия Оператора в Роскомнадзоре или в суде.']) +
          '<p>Запросы направляйте на ' + EMAIL + (PHONE ? ' или по телефону ' + PHONE : '') + '.</p>' +
          '<h2>9. Cookie</h2><p>Как сайт использует cookie и локальное хранилище браузера, описано на странице <a href="cookies.html">«Cookie»</a>.</p>' +
          '<h2>10. Изменения политики</h2><p>Актуальная редакция всегда опубликована на этой странице и действует с момента публикации.</p>';
      }
    },
    consent: {
      title: 'Согласие на обработку персональных данных',
      body: function () {
        return '<p>Я, действуя свободно, своей волей и в своём интересе, даю согласие ' + OP + ' (ИНН ' + INN + ', адрес: ' + ADDR + ') на обработку моих персональных данных в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных».</p>' +
          '<h2>Перечень данных</h2><p>Имя; номер телефона, адрес почты или ник в мессенджере; ' + (data.length ? data.join('; ') + '; ' : '') + 'иные сведения, которые я указал(а) в форме заявки на сайте ' + SITE + '.</p>' +
          '<h2>Цели обработки</h2><p>Обработка моей заявки, обратная связь, подготовка расчёта, записи или договора.</p>' +
          '<h2>Действия с данными</h2><p>Сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, передача (предоставление, доступ) в случаях, указанных в <a href="privacy.html">политике</a>, блокирование, удаление, уничтожение. С использованием средств автоматизации и без них.</p>' +
          '<h2>Срок действия и отзыв</h2><p>Согласие действует до достижения целей обработки или до его отзыва. Отозвать согласие можно письмом на ' + EMAIL + '.</p>' +
          '<p>Я подтверждаю, что ознакомлен(а) с <a href="privacy.html">политикой обработки персональных данных</a>.</p>';
      }
    },
    cookies: {
      title: 'Cookie и локальное хранилище',
      body: function () {
        return '<p class="doc-meta">Сайт: ' + SITE + ' · Оператор: ' + OP + ' · Дата: ' + DATE + '</p>' +
          '<h2>Что это</h2><p>Cookie и локальное хранилище — небольшие записи, которые сайт сохраняет в вашем браузере.</p>' +
          '<h2>Категории</h2><table><thead><tr><th>Категория</th><th>Зачем</th><th>Можно отключить</th></tr></thead><tbody>' +
          '<tr><td>Необходимые</td><td>Запоминают ваш выбор в баннере cookie. В демо-версии шаблона здесь же хранятся тестовые заявки.</td><td>Нет</td></tr>' +
          '<tr><td>Аналитические</td><td>' + (metrika ? 'Обезличенная статистика посещений (Яндекс Метрика). Включаются только после вашего согласия.' : 'Сейчас на сайте не используются.') + '</td><td>Да</td></tr>' +
          '<tr><td>Маркетинговые</td><td>' + (L.marketingCookies ? esc(L.marketingCookies) : 'Сейчас на сайте не используются.') + '</td><td>Да</td></tr>' +
          '</tbody></table>' +
          '<h2>Как изменить выбор</h2><p>Нажмите «Настройки cookie» в подвале сайта или очистите данные сайта в настройках браузера.</p>' +
          '<h2>Контакты</h2><p>Вопросы об обработке данных: ' + EMAIL + '.</p>';
      }
    }
  };

  var d = DOCS[doc];
  if (!d) return;
  var custom = L.docs && typeof L.docs[doc] === 'string' && L.docs[doc].trim();
  document.title = d.title + (B.name ? ' — ' + B.name : '');
  if (demo) { var m = document.createElement('meta'); m.name = 'robots'; m.content = 'noindex, nofollow'; document.head.appendChild(m); }
  // акцент бренда красит ссылки, только если читается на светлом фоне документа (WCAG AA 4.5:1);
  // светлый или жёлтый акцент тёмных шаблонов оставляет цвет ссылок по умолчанию
  var accent = B.colors && B.colors.accent;
  var lum = function (hex) {
    var m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(String(hex || '').trim());
    if (!m) return null;
    var h = m[1].length === 3 ? m[1].replace(/./g, '$&$&') : m[1];
    var c = [0, 2, 4].map(function (i) { var v = parseInt(h.substr(i, 2), 16) / 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); });
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
  };
  var la = lum(accent), lp = lum('#fbfaf7');
  if (la != null && (lp + 0.05) / (la + 0.05) >= 4.5) document.documentElement.style.setProperty('--accent', accent);
  // у страниц документа нет своей иконки — без неё браузер запрашивает /favicon.ico и получает 404
  if (!document.querySelector('link[rel~="icon"]')) {
    var icon = document.createElement('link');
    icon.rel = 'icon';
    icon.href = 'data:image/svg+xml,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="' + (accent || '#1f5c4a') + '"/></svg>');
    document.head.appendChild(icon);
  }

  var warn = L.approved === true && custom ? '' :
    '<div class="doc-warn" role="note"><b>Шаблон документа.</b> Текст основан на общем шаблоне 152-ФЗ и не подтверждает, что сайт соответствует всем требованиям. ' +
    'Владелец сайта заполняет поля <mark class="fill">[В СКОБКАХ]</mark> и проверяет текст с юристом, затем ставит <code>legal.approved: true</code> в config.js.</div>';

  document.getElementById('doc').innerHTML =
    '<a class="back" href="../index.html">← Вернуться на сайт' + (B.name ? ' «' + esc(B.name) + '»' : '') + '</a>' +
    (demo ? '<p class="doc-demo">Демонстрационный шаблон. Данные приведены для примера.</p>' : '') +
    '<h1>' + esc(d.title) + '</h1>' + warn + (custom ? L.docs[doc] : d.body());
})();
